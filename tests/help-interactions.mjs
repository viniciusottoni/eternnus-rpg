import { chromium } from '../artifacts/qa-runtime/node_modules/playwright/index.mjs';
import { startEnvironment } from './support/harness.mjs';
import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const dir='artifacts/qa/ajuda-contextual', checks=[], errors=[];
await mkdir(dir,{recursive:true});
const env=await startEnvironment({port:5259});
let browser;
const ok=(value,text)=>{assert.ok(value,text);checks.push(text);console.log(text);};
try {
  const master=await env.verifiedClient('help.interactions@example.test','Mestre');
  const campaign=await master('/api/campaigns','POST',{name:'Interações da ajuda',description:'',rpgSystemId:'00000000-0000-4000-8000-000000000001',playMode:'tactical'});
  const session=await master(`/api/campaigns/${campaign.id}/sessions`,'POST',{title:'Ensaio',objective:'',mapKind:'tileset',mapKey:'bridge'});
  await master(`/api/sessions/${session.id}/join`,'POST',{},204);
  browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
  let context=await browser.newContext({viewport:{width:1440,height:900},serviceWorkers:'block'});
  let page=await context.newPage();
  page.on('pageerror',(e)=>errors.push(e.message));
  page.on('console',(m)=>{if(/Content Security Policy|Refused to (apply|execute|load)/i.test(m.text()))errors.push(m.text());});
  let release;
  const gate=new Promise((resolve)=>{release=resolve;});
  await page.route('**/js/help/conta.js',async(route)=>{await gate;await route.continue();});
  await page.goto(env.origin+'/#login');
  const first=page.locator('[data-help="conta.acesso.persistencia"]');
  await first.waitFor();await page.waitForFunction(()=>!document.querySelector('#app').inert);
  await first.click();await page.getByText('Carregando ajuda…').waitFor();
  ok(await page.locator('#help-popup').evaluate((e)=>document.activeElement===e),'carregando recebe foco antes de chegar o catálogo');
  await page.screenshot({path:dir+'/carregando-catalogo.png'});
  release();await page.getByText('Você pode manter o login por 14 dias fixos.',{exact:false}).waitFor();
  await page.locator('[data-help="conta.acesso.social"]').click();
  await page.getByRole('heading',{name:'Acesso com Google ou Discord',exact:true}).waitFor();
  ok(await page.locator('#help-popup').count()===1,'abrir outro conceito reutiliza o único popup');
  ok(await first.getAttribute('aria-expanded')==='false','troca de conceito recolhe o gatilho anterior');
  await page.locator('.auth-brand').click({position:{x:10,y:10}});
  await page.waitForFunction(()=>!document.querySelector('#help-popup').matches(':popover-open'));
  ok(await page.locator('[data-help="conta.acesso.social"]').evaluate((e)=>document.activeElement===e),'clique fora devolve foco ao gatilho atual');
  const unknown=await page.evaluate(async()=>{const {helpButton}=await import('/js/help.js');return helpButton('mesa.inexistente.chave','Inexistente');});
  ok(unknown==='','chave inexistente não produz botão nem quebra a tela');
  const retryContext=await browser.newContext({viewport:{width:1440,height:900},serviceWorkers:'block'}),retryPage=await retryContext.newPage();
  let attempts=0;
  await retryPage.route('**/js/help/conta.js',async(route)=>{if(++attempts===1)await route.abort();else await route.continue();});
  await retryPage.goto(env.origin+'/#login');await retryPage.locator('[data-help="conta.acesso.persistencia"]').waitFor();await retryPage.waitForFunction(()=>!document.querySelector('#app').inert);
  await retryPage.locator('[data-help="conta.acesso.persistencia"]').click();await retryPage.getByText('Não foi possível carregar esta ajuda.').waitFor();
  await retryPage.getByRole('button',{name:'Tentar novamente',exact:true}).click();
  await retryPage.getByText('Você pode manter o login por 14 dias fixos.',{exact:false}).waitFor({timeout:8000});
  ok(attempts>=2,'nova tentativa recupera falha de carregamento');
  await retryContext.close();
  await context.close();
  context=await browser.newContext({viewport:{width:1440,height:900},serviceWorkers:'block'});
  await context.addCookies(master.cookieHeader().split('; ').filter(Boolean).map((s)=>{const i=s.indexOf('=');return{name:s.slice(0,i),value:s.slice(i+1),url:env.origin};}));
  page=await context.newPage();page.on('pageerror',(e)=>errors.push(e.message));
  await page.goto(env.origin+`/#table/${campaign.id}`);await page.locator('#t-turn .turn-actions').waitFor();await page.waitForFunction(()=>!document.querySelector('#app').inert);
  await page.locator('[data-action=t-fog-group][data-id=reveal]').click();
  const source = page.locator('#app [data-help="mesa.nevoa.ferramentas"]');
  const original = await source.elementHandle();
  await source.click();
  await page.locator('#help-popup:popover-open').waitFor();
  await master(`/api/sessions/${session.id}/notes`,'POST',{content:'Atualização para testar foco',shared:true},204);
  await page.getByText('Atualização para testar foco',{exact:true}).first().waitFor();
  ok(await original.evaluate((e)=>!e.isConnected),'consulta ao vivo substitui realmente o gatilho da ajuda');
  ok(await page.locator('#help-popup').evaluate((e)=>e.matches(':popover-open')&&document.activeElement===e),'popup e foco sobrevivem ao re-render ao vivo');
  await page.keyboard.press('Escape');
  ok(await source.evaluate((e)=>document.activeElement===e),'fechar retorna ao gatilho substituído pelo re-render');
  ok(await page.locator('[data-action=t-fog-group][data-id=reveal]').getAttribute('aria-pressed')==='true','primeiro Esc fecha só ajuda e mantém modo do mapa');
  await page.locator('.board-canvas').focus();await page.keyboard.press('Escape');
  ok(await page.locator('[data-action=t-fog-group][data-id=reveal]').getAttribute('aria-pressed')==='false','segundo Esc cancela o modo do mapa');
  let requests=0;page.on('request',(req)=>{if(req.method()==='POST'&&req.url().endsWith('/roll-requests'))requests++;});
  const disabled=page.locator('[data-action=t-request][aria-disabled=true]').first();
  await disabled.focus();await page.keyboard.press('Enter');
  ok(requests===0,'ação aria-disabled bloqueia teclado antes do handler');
  ok((await disabled.getAttribute('aria-describedby'))?.length>0,'motivo de indisponibilidade é associado e alcançável');
  ok(await disabled.evaluate((e)=>Number(getComputedStyle(e).opacity)<=0.6),'aria-disabled preserva o estado visual de indisponibilidade');
  await page.screenshot({path:dir+'/acao-indisponivel-desktop.png'});
  await page.locator('#app [data-help="mesa.interface.apresentacao"]').click();
  await page.locator('#help-popup:popover-open').waitFor();
  await page.locator('#app [data-help="mesa.interface.apresentacao"]').evaluate((e)=>e.remove());
  await page.waitForFunction(()=>!document.querySelector('#help-popup').matches(':popover-open'));
  ok(await page.evaluate(()=>document.activeElement!==document.body),'gatilho removido fecha ajuda sem largar foco no body');
  await page.goto(env.origin+`/#session/${session.id}`);
  const historyHelp=page.locator('[data-help="sessoes.historico.alteracoes"]');
  await historyHelp.waitFor();await page.waitForFunction(()=>!document.querySelector('#app').inert);
  await historyHelp.focus();await page.keyboard.press('Enter');await page.locator('#help-popup:popover-open').waitFor();
  ok(await page.locator('#help-popup').evaluate((e)=>document.activeElement===e),'histórico aberto diretamente reconhece a audiência do Mestre');
  await page.screenshot({path:dir+'/historico-desktop.png'});
  await page.keyboard.press('Escape');
  ok(await historyHelp.evaluate((e)=>document.activeElement===e),'histórico devolve foco por teclado');
  ok(errors.length===0,'interações sem erro de página ou CSP');
  console.log(JSON.stringify({checks:checks.length,errors}));
}catch(error){errors.push(error.stack);console.error(error);if(browser)for(const c of browser.contexts())for(const p of c.pages()){console.error(p.url(),(await p.locator('body').innerText()).slice(-1500));await p.screenshot({path:dir+'/interactions-failure.png',fullPage:true}).catch(()=>{});}process.exitCode=1;}
finally{await writeFile(dir+'/interactions.json',JSON.stringify({checks,errors},null,2));await browser?.close();await env.stop();}
